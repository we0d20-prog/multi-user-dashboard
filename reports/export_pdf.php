<?php

require "../includes/auth_check.php";
require "../includes/permissions.php";
require "../config/db.php";

// تحميل مكتبات Composer ومنها Dompdf
require "../vendor/autoload.php";

// استدعاء الكلاسات الخاصة بمكتبة Dompdf
use Dompdf\Dompdf;
use Dompdf\Options;

// إذا لم يكن لدى المستخدم صلاحية reports.view
if (!hasPermission('reports.view'))
{
    die("Access Denied");
}

// استعلام يجلب المستخدمين مع اسم الدور الخاص بكل مستخدم
$stmt = $pdo->query("
SELECT
users.id,
users.name,
users.email,
roles.role_name,
users.status

FROM users

LEFT JOIN roles
ON users.role_id = roles.id

ORDER BY users.id ASC
");

$users = $stmt->fetchAll(PDO::FETCH_ASSOC);

// جلب اسم الموقع واسم الشركة والشعار
$settings = $pdo->query("
SELECT
site_name,
company_name,
logo

FROM settings

LIMIT 1
")->fetch(PDO::FETCH_ASSOC);

// متغير سيحتوي على كود HTML الخاص بالشعار
$logoHtml = "";

// التأكد من وجود اسم للشعار وأن الملف موجود فعلاً
if (
    !empty($settings['logo'])
    &&
    file_exists("../uploads/logos/" . $settings['logo'])
)
{
    // الحصول على المسار الحقيقي للصورة
    $imagePath = realpath("../uploads/logos/" . $settings['logo']);

    // حتى يستطيع Dompdf عرضها داخل الـ PDF
    $imageData = base64_encode(file_get_contents($imagePath));

    // استخراج امتداد الصورة (png - jpg ...)
    $imageType = pathinfo($imagePath, PATHINFO_EXTENSION);

    // إنشاء كود HTML الخاص بالصورة
    $logoHtml = '
    <img
    src="data:image/' . $imageType . ';base64,' . $imageData . '"
    width="90">
    <br><br>
    ';
}

// بداية الصفحة
$html = '

<div style="text-align:center;">

' . $logoHtml . '

<h2>' . $settings['site_name'] . '</h2>

<h3>Users Report</h3>

<p>

<strong>Company :</strong>

' . $settings['company_name'] . '

</p>

<p>

<strong>Generated At :</strong>

' . date("Y-m-d H:i:s") . '

</p>

<p>
<strong>Generated By :</strong> '.htmlspecialchars($_SESSION['user_name']).'
</p>

</div>

<br>

<style>
table {
    border-collapse: collapse;
    width: 100%;
}
th {
    background-color: #343a40;
    color: white;
    text-align: center;
}
td {
    text-align: center;
}
th, td {
    border: 1px solid #000;
    padding: 8px;
}
</style>

<table>
<thead>
<tr>
<th>ID</th>
<th>Name</th>
<th>Email</th>
<th>Role</th>
<th>Status</th>
</tr>
</thead>
<tbody>

<br>
';

/* إضافة بيانات المستخدمين داخل الجدول*/

// المرور على جميع المستخدمين
foreach ($users as $user)
{
    // إضافة صف جديد لكل مستخدم
    $html .= '

    <tr>

        <td>' . $user['id'] . '</td>
        <td>' . $user['name'] . '</td>
        <td>' . $user['email'] . '</td>
        <td>' . $user['role_name'] . '</td>
        <td>' . $user['status'] . '</td>

    </tr>

    ';
}

$html .= '

</tbody>

</table>

<p>
    <strong>Total User :</strong> '.count($users).'
</p>

';

// إنشاء كائن للإعدادات
$options = new Options();

// تفعيل دعم HTML5
$options->set('isHtml5ParserEnabled', true);

// إنشاء كائن Dompdf
$dompdf = new Dompdf($options);

// تحميل محتوى HTML داخل المكتبة
$dompdf->loadHtml($html);

// تحديد حجم واتجاه الورقة
// A4 - Portrait (عمودي)
$dompdf->setPaper('A4', 'portrait');

$html .= '
<hr>
<p style="text-align:center;font-size:12px;">
'.$settings['site_name'].' | Generated on '.date('Y-m-d').'
</p>
';
// تحويل الـ HTML إلى PDF
$dompdf->render();

/*إرسال الملف للمستخدم*/

// تنزيل الملف باسم Users_Report.pdf
$dompdf->stream(
    "Users_Report.pdf",
    [
        "Attachment" => true
    ]
);

exit;